    def test_reflection_closure_and_manual_adapter_agreement(self):
        for c in self.result['candidates']:
            d=c['prescription'];a=adapt_external(d)
            points=np.array([a.source.position,*[m.vertex for m in a.reflectors],a.target.position])
            segments=np.diff(points,axis=0);lengths=np.linalg.norm(segments,axis=1);directions=segments/lengths[:,None]
            np.testing.assert_allclose(directions[0],a.source.direction,atol=1e-12)
            np.testing.assert_allclose(directions[-1],a.target.direction,atol=1e-12)
            for i,m in enumerate(a.reflectors):
                n=np.array(m.normal);reflected=directions[i]-2*np.dot(directions[i],n)*n
                np.testing.assert_allclose(reflected,directions[i+1],atol=1e-12)
                self.assertLess(np.dot(directions[i],n),0)
            np.testing.assert_allclose(lengths,c['evaluation']['geometry']['lengths'],atol=1e-15)
            manual=json.loads(json.dumps(evaluate_external(d)))
            self.assertEqual(manual,c['evaluation'])

    def test_analytic_power_branches_independent_abcd(self):
        for qs in (0.0002j,0.0003+0.0006j,-0.0004+0.0003j):
            for a,b,c,p1,p2 in ((.001,.002,.001,1000.,1000.),(.0007,.0011,.0009,-200.,700.)):
                qt=matrix_q(qs,a,b,c,p1,p2)
                solutions=power_pairs(qs,qt,a,b,c)
                self.assertTrue(solutions)
                self.assertTrue(any(abs(x-p1)<1e-6 and abs(y-p2)<1e-6 for x,y in solutions))
                for x,y in solutions:
                    self.assertLess(abs(matrix_q(qs,a,b,c,x,y)-qt)/abs(qt),1e-10)
        self.assertEqual(power_pairs(.001j,.001j,.001,.1,.001),[])

    def test_generated_curvatures_independent_matrix_and_surface_derivative(self):
        for c in self.result['candidates']:
            adapted=adapt_external(c['prescription']);lengths=c['evaluation']['geometry']['lengths']
            dirs=np.array(c['evaluation']['geometry']['directions']);powers=[]
            for j,m in enumerate(adapted.reflectors):
                cosine=-float(np.dot(dirs[j],m.normal));angle=math.acos(cosine)
                k=m.curvatures;p=(2*k[0]/cosine,2*k[1]*cosine);powers.append(p)
                for axis in (0,1):
                    eps=1e-9
                    hp,sp=exact_surface_ray(eps,axis,angle,*k);hm,sm=exact_surface_ray(-eps,axis,angle,*k)
                    np.testing.assert_allclose(-(sp-sm)/(hp-hm),p[axis],rtol=2e-6,atol=1e-5)
            for axis,(qs,qt) in enumerate(zip(adapted.source.mode.q,adapted.target.mode.q)):
                actual=matrix_q(qs,*lengths,powers[0][axis],powers[1][axis])
                self.assertLess(abs(actual-qt)/abs(qt),1e-10)

    def test_selected_candidates_independent_fresnel_sampling_and_window(self):
        # Reuse existing independent Fresnel reference, no production q/power calls.
        for c in self.result['candidates']:
            a=adapt_external(c['prescription']);lengths=c['evaluation']['geometry']['lengths']
            cos=c['evaluation']['geometry']['cosines'];etas=[]
            for count,span in ((16384,.004),(32768,.006)):
                dx=span/count;x=(np.arange(count)-count/2)*dx;eta=1.
                for axis,width in enumerate((8e-6,12e-6)):
                    field=sampled_field(x,width,0.)
                    for j,m in enumerate(a.reflectors):
                        field=fresnel(field,dx,lengths[j])
                        p=2*m.curvatures[axis]/cos[j] if axis==0 else 2*m.curvatures[axis]*cos[j]
                        field*=np.exp(1j*np.pi/1.31e-6*p*x*x)
                    field=fresnel(field,dx,lengths[2])
                    self.assertAlmostEqual(float(np.sum(abs(field)**2)*dx),1.,places=11)
                    eta*=float(abs(np.vdot(sampled_field(x,width,0.),field)*dx)**2)
                etas.append(eta)
                self.assertAlmostEqual(eta,c['evaluation']['gaussian_mode_matching']['normalized_mode_overlap'],places=9)
            self.assertAlmostEqual(*etas,places=10)

