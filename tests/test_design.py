def matrix_q(q,a,b,c,p1,p2):
    translation=lambda l:np.array([[1.,l],[0.,1.]])
    power=lambda p:np.array([[1.,0.],[-p,1.]])
    m=translation(c)@power(p2)@translation(b)@power(p1)@translation(a)
    return (m[0,0]*q+m[0,1])/(m[1,0]*q+m[1,1])


