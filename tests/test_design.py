    def test_nonwaist_q_only_and_rigid_rotation(self):
        d=fixture()
        for name in ('source','target'):
            node=d[name];node.pop('mfd_ts_m');node.pop('wavefront_curvature_ts_per_m')
            node['complex_q_ts_m']={'value':[[.0001,.0003],[-.0001,.0005]],'unit':'m','provenance':'synthetic','source':'nonwaist test','uncertainty':None}
        self.assertEqual(design_two_ports(d)['status'],'Computed')
        rotation=np.array([[0.,0.,1.],[1.,0.,0.],[0.,1.,0.]])
        for name in ('source','target'):
            node=d[name]
            for key in ('position_m','propagation_direction','sagittal_axis'):
                node[key]['value']=(rotation@node[key]['value']).tolist()
            node['reference_plane']['value']['origin_m']=node['position_m']['value'].copy()
            node['reference_plane']['value']['normal']=node['propagation_direction']['value'].copy()
        self.assertEqual(design_two_ports(d)['status'],'Computed')

